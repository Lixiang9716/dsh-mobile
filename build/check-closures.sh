#!/bin/sh
# build/check-closures.sh — the closures gate: every committed host copy of
# the canonical runtime/dsh closure is byte-identical to its source, or a
# named file fails the gate.
#
# Why this is a gate and not a convention (rule 1, gates over prose): each
# host embeds a COPY of the canonical closure (Android assets/, HarmonyOS
# rawfile/, the iOS generated C arrays) because the platform build systems
# consume committed bytes; the copies are made by the per-host stagers, and
# drift in them is SILENT — CI re-stages before building, so a stale
# committed copy builds green while lying to every reader of the tree (the
# m5 surprise ledger, measured again on 2026-09-23: five harmony rawfile
# files and two three-way files sat drifted on main with dev/harmonyos
# green). This check makes the committed state itself a claim that can fail.
#
# Per host:
#   android  hosts/android/ci/stage-spine-closure.sh --check
#   harmony  hosts/harmony/ci/vendor-official.sh --check
#   ios      run hosts/ios/gen.sh and demand exit 0 (the D9 flip: the
#            generated bytes — App/Generated/, DSHSpike.xcodeproj/ — are no
#            longer committed, so there is no copy in the index to
#            byte-compare; the claim is "the deterministic generator runs and
#            succeeds on this tree", contract/proposals/
#            2026-09-29-generated-bundles.md).
#
# The iOS leg since the flip: generation is deterministic (order-stable walks,
# byte-stable across runs — 908c3bdd), so exit 0 IS the freshness claim; the
# outputs are gitignored build output and nothing is written back into the
# index. Where xcodegen is absent (Linux gate hosts) only the bundle half
# (gen_bundle_header.py, pure python3 — the half that embeds the runtime/dsh
# closure) is demanded exit 0, loudly; the project half is enforced on every
# macOS build, which now runs gen.sh ahead of xcodebuild.
#
# usage: build/check-closures.sh   exit 0 = every closure fresh
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
cd "$ROOT"

FAIL=0

echo "closures: android (assets vs runtime/dsh pins)"
hosts/android/ci/stage-spine-closure.sh --check || FAIL=1

echo ""
echo "closures: harmony (rawfile vs runtime/dsh pins)"
hosts/harmony/ci/vendor-official.sh --check || FAIL=1

echo ""
echo "closures: ios (generate; the claim is gen.sh exits 0, not bytes in the index)"
IOS_OK=0
if command -v python3 >/dev/null 2>&1; then
    # gen.sh's inputs must be on disk first: xcodegen references the vendored
    # quickjs sources, and the bundle embeds the pinned dsh/npm closure. The
    # materialize step belongs to the caller (gov.yml materializes before
    # `gov run`; build/build.sh sync ios does the same) — absent inputs are a
    # misconfiguration and fail loud naming the fix (rule 5), never silently.
    IOS_INPUTS=1
    for d in runtime/dsh/vendor/quickjs-ng runtime/dsh/vendor/dsh runtime/dsh/vendor/npm; do
        [ -d "$d" ] || {
            echo "::error::closures: ios generation input $d absent — run runtime/dsh/vendor/ensure.sh && runtime/dsh/vendor/ensure-dsh.sh first" >&2
            IOS_INPUTS=0
        }
    done
    if [ "$IOS_INPUTS" = "1" ]; then
        if command -v xcodegen >/dev/null 2>&1; then
            if sh hosts/ios/gen.sh >/dev/null 2>&1; then
                IOS_OK=1
            else
                echo "::error::closures: hosts/ios/gen.sh failed — the generator must succeed on this tree (run it without output suppression for the traceback)" >&2
            fi
            [ "$IOS_OK" = "1" ] && echo "closures: ios generation green (bundle + project, gen.sh exit 0)"
        else
            # No xcodegen on this host (the Linux gates job): the bundle half
            # is pure python3 and embeds the runtime/dsh closure — the half
            # whose freshness "closures" is about. The project half is
            # enforced on every macOS build (dev/ios installs xcodegen and
            # runs gen.sh ahead of xcodebuild). Loud, never silent.
            if python3 hosts/ios/Tools/gen_bundle_header.py >/dev/null 2>&1; then
                IOS_OK=1
            else
                echo "::error::closures: gen_bundle_header.py failed on this tree" >&2
            fi
            [ "$IOS_OK" = "1" ] && echo "closures: ios bundle generation green; project half (xcodegen) absent on this host — enforced on the macOS builds that run gen.sh before xcodebuild" >&2
        fi
    fi
    [ "$IOS_OK" = "1" ] || FAIL=1
else
    echo "closures: SKIP ios (python3 absent on this host)" >&2
fi

echo ""
if [ "$FAIL" = "0" ]; then
    echo "closures: android + harmony committed copies byte-identical; ios generator green"
else
    echo "::error::closures: drift found — re-stage with build/build.sh sync <platform>" >&2
    exit 1
fi
