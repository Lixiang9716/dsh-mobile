/** Run everything the imported specs collected; report per test to the
 * caller's sink. Returns {passed, failed, skipped, failures}. A test that
 * never settles is the suite's hang class (no timer seam to cut it short) —
 * the sink sees its 'start' before it runs, so the stream names the exact
 * test a hang froze on. */
/** The test-context argument vitest hands every test fn (module level for
 * size): skip() raises a marker the runner classifies as 'skipped' (vitest
 * never counts a context-skip a failure); `task` is the running test's
 * handle — task.timeout is the test's time budget in ms (specs pass it as a
 * DEADLINE value: waitForFile(marker, task.timeout, signal)); budget
 * re-arming stays on TestRunner.getCurrentTest().timeout(ms). The signal
 * aborts when the test finishes; tests thread it into deadline helpers and
 * call signal.throwIfAborted() mid-body. */
const makeTestContext = (t, controller) => ({
  skip: (note) => {
    const skipError = new Error(note ?? 'skipped by test context');
    skipError.__dshTestContextSkip = true;
    throw skipError;
  },
  task: {
    get name() { return t.name; },
    get timeout() { return t.timeoutMs ?? 5000; },
  },
  signal: controller.signal,
});

/** Classify one failed test into the report + E2E sink (module level for
 * size): the failure row carries name/message/stack; DSH_R3E_DEBUG=1 adds
 * the full raw error JSON to the structured log for the stall triage. */
const reportTestFailure = (t, error, report, sink) => {
  report.failed += 1;
  report.failures.push({
    name: t.name,
    message: error?.message ?? String(error),
    stack: String(error?.stack ?? '').split('\n').slice(1, 5).join(' | '),
  });
  const launchEnv = (() => {
    try { const raw = globalThis.__dshLaunchEnv?.(); return raw ? JSON.parse(raw) : {}; } catch { return {}; }
  })();
  if (globalThis.__DSH_LOG_SINK__ && launchEnv.DSH_R3E_DEBUG === '1') {
    const rawJson = (() => { try { return JSON.stringify(error); } catch { return String(error); } })();
    globalThis.__DSH_LOG_SINK__(JSON.stringify({ scenario: 'upstream.suite', event: 'debug/failure', name: t.name.slice(0, 120), cls: error?.constructor?.name, stack: String(error?.stack ?? '').slice(0, 900), raw: rawJson }));
  }
  sink(t.name, 'fail', error?.message ?? String(error));
};

/** Run ONE collected test (module level for size): beforeEach hooks, the
 * context argument (makeTestContext), the pass/skip/fail classification into
 * the report + E2E sink, and the afterEach hooks (their failures never mask
 * the verdict). */
const runOneTest = async (t, report, sink) => {
  if (typeof t.fn !== 'function') { report.skipped += 1; sink(t.name, 'skipped'); return; }
  sink(t.name, 'start');
  runningTest = t;
  try {
    for (const hook of t.hooks.beforeEach) await hook();
    // vitest hands every test fn a CONTEXT as its first argument — tests
    // that destructure it (`async ({ skip }) => …`) throw
    // "Cannot convert undefined or null to object" when it is missing
    // (stream-rebind). See makeTestContext for the documented subset.
    const controller = new AbortController();
    try {
      await t.fn(makeTestContext(t, controller));
    } finally {
      controller.abort();
    }
    report.passed += 1;
    sink(t.name, 'pass');
  } catch (error) {
    if (error?.__dshTestContextSkip) {
      report.skipped += 1;
      sink(t.name, 'skipped');
      return;
    }
    reportTestFailure(t, error, report, sink);
  } finally {
    runningTest = null;
    for (const hook of t.hooks.afterEach) {
      try { await hook(); } catch { /* afterEach failures do not mask the verdict */ }
    }
  }
};

export const runCollected = async (sink) => {
  const report = { passed: 0, failed: 0, skipped: 0, failures: [] };
  // Suite-level hooks reject with whatever the spec threw — including bare
  // null/undefined (the otel egress afterAll rejected with null, which
  // escaped as a scenario failure with the reason string "null" and no
  // attribution). Wrap both ends: the hook's identity and the thrown value
  // are named, never silently re-thrown (rule 5).
  const suiteHookError = (phase, error) => new Error(
    `${phase} hook failed: ${error === null ? 'null (rejection with null)' : error instanceof Error ? error.message : String(error)}`,
  );
  for (const setup of suite.before) {
    try {
      await setup();
    } catch (error) {
      throw suiteHookError('beforeAll', error);
    }
  }
  for (const t of suite.tests) {
    await runOneTest(t, report, sink);
  }
  for (const teardown of suite.after) {
    try {
      await teardown();
    } catch (error) {
      // vitest counts an afterAll failure as a suite error, not a test
      // failure — surface it as its own failure row AND a named rejection,
      // so the scenario verdict carries the hook's name instead of "null".
      report.failed += 1;
      const named = suiteHookError('afterAll', error);
      report.failures.push({ name: 'afterAll', message: named.message, stack: String(error?.stack ?? '').split('\n').slice(1, 5).join(' | ') });
      sink('afterAll', 'fail', named.message);
      throw named;
    }
  }
  return report;
};

/** vitest's TestRunner face — the corpus specs ask the runner for the test
 * they are INSIDE (`TestRunner.getCurrentTest().timeout(ms)` re-arms that
 * test's time budget). The runtime has no wall-clock seam to enforce a
 * budget (the runCollected hang note above), so the request is recorded on
 * the test record and surfaced through the sink instead of being silently
 * dropped. Outside a run (collection time) the CURRENT test is the last one
 * collected, which is what module-scope callers mean. */
let runningTest = null;
export const TestRunner = {
  getCurrentTest() {
    const current = runningTest ?? suite.tests[suite.tests.length - 1];
    if (current === undefined) failWith('harness: TestRunner.getCurrentTest() — no test is running or collected');
    return {
      timeout: (ms) => { current.timeoutMs = ms; },
      name: current.name,
    };
  },
};

