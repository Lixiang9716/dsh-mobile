/** The expect() chain. The second parameter is vitest's optional custom
 * failure MESSAGE (`expect(actual, message)`) — measured 2026-09-27: treating
 * a string second argument as the negation flag (its old role in the
 * internal resolves/rejects chain) inverted every assertion of a two-arg
 * expect, so `expect(x, id).toBe(true)` failed as "expected NOT to be true".
 * A string here is a failure PREFIX; the boolean stays the negation flag. */
const comparisonMatchers = (actual, check) => ({
  toBeGreaterThan(n) { check(actual > n, `> ${n} (got ${fmt(actual)})`); },
  toBeGreaterThanOrEqual(n) { check(actual >= n, `>= ${n} (got ${fmt(actual)})`); },
  toBeLessThan(n) { check(actual < n, `< ${n} (got ${fmt(actual)})`); },
  toBeLessThanOrEqual(n) { check(actual <= n, `<= ${n} (got ${fmt(actual)})`); },
});

/** Property-path matchers. */
const propertyMatchers = (actual, check) => ({
  toHaveProperty(key, value) {
    const parts = Array.isArray(key) ? key : key.split('.');
    let at = actual;
    for (const p of parts) {
      // vitest reads through PROPERTY ACCESS: a class instance's methods
      // (`start`/`close` on the MCP transports — the createTransport table,
      // W4-M 2026-09-28) live on the PROTOTYPE, so an own-key-only walk
      // failed every method face. Absent = undefined AND no own key.
      if (at === null || at === undefined || (at[p] === undefined && !Object.prototype.hasOwnProperty.call(at, p))) {
        check(false, `property "${key}"`);
        return;
      }
      at = at[p];
    }
    if (arguments.length > 1) {
      check(deepEqual(at, value), `property "${key}" = ${fmt(value)} (got ${fmt(at)})`);
    } else {
      check(true);
    }
  },
});

/** The toThrow family (function-throwing assertions). */
/** The thrown-message comparison arms of toThrow (module level for size):
 * an object with a `message` string compares through it (jest-compatible);
 * a thrown STRING/number stringifies and compares against that (R3-G1,
 * 2026-09-28). JSON-RPC errors keep the REAL error in `.data` while
 * `message` collapses to "Internal error" — surfaced in the verdict (W5-Q,
 * 2026-09-28). An ERROR INSTANCE expectation compares by message and
 * identity — jest's contract for this form (measured 2026-09-28). */

const makeExpect = (actual, negatedOrMessage = false, customMessage = '') => {
  // The exported expect() is this function, so vitest's `expect(actual,
  // message)` lands the message in the SECOND slot; the boolean form is how
  // the internal .not/.resolves/.rejects machinery re-enters.
  let negated = negatedOrMessage === true;
  let message = customMessage;
  if (typeof negatedOrMessage === 'string') message = negatedOrMessage;
  const prefix = typeof message === 'string' && message.length > 0
    ? `${message}: `
    : '';
  const check = (ok, description) => {
    if (negated ? ok : !ok) {
      failWith(`${prefix}expected ${negated ? 'NOT ' : ''}${description}`);
    }
  };
  const api = {
    ...callMatchers(actual, check),
    ...comparisonMatchers(actual, check),
    ...valueMatchers(actual, check),
    ...identityMatchers(actual, check),
    ...propertyMatchers(actual, check),
    ...throwMatchers(actual, check),
    // vitest unwraps a FUNCTION subject by calling it before awaiting
    // (`typeof obj === "function" ? obj() : obj`) — expect(async fn).resolves
    // / .rejects is the corpus's dominant form (api remotes.host, session).
    resolves: makeAsyncChain(() => Promise.resolve(typeof actual === 'function' ? actual() : actual), negated, true, message),
    rejects: makeAsyncChain(() => Promise.resolve(typeof actual === 'function' ? actual() : actual).then(
      () => failWith('expected the promise to reject, but it resolved'),
      (error) => error,
    ), negated, false, message),
  };
  // .not is LAZY: constructing it eagerly would recurse (each negated
  // matcher set builds its own .not, forever). The custom failure MESSAGE
  // rides along (W4-N 2026-09-28: vitest's `expect(x, msg).not.toContain()`
  // throws with msg as the failure text and storage-policy's guard asserts
  // that message via rejects.toThrow — dropping it broke the match).
  let negatedApi = null;
  Object.defineProperty(api, 'not', {
    get: () => {
      if (negatedApi === null) negatedApi = makeExpect(actual, !negated, message);
      return negatedApi;
    },
  });
  return api;
};
const makeAsyncChain = attachAsyncChain(makeExpect, failWith);

